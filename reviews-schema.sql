-- Public product reviews for the TAVRA storefront.
-- Visitors submit reviews through the Node API; the API validates each review.

CREATE TABLE IF NOT EXISTS public.product_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  reviewer_name VARCHAR(60) NOT NULL CHECK (char_length(trim(reviewer_name)) BETWEEN 2 AND 60),
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review_text VARCHAR(1200) NOT NULL CHECK (char_length(trim(review_text)) BETWEEN 10 AND 1200),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  is_approved BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS product_reviews_product_created_idx
  ON public.product_reviews (product_id, created_at DESC);

ALTER TABLE public.product_reviews ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.product_reviews TO anon, authenticated;

DROP POLICY IF EXISTS product_reviews_public_read ON public.product_reviews;
CREATE POLICY product_reviews_public_read
  ON public.product_reviews
  FOR SELECT
  TO anon, authenticated
  USING (is_approved = TRUE);
